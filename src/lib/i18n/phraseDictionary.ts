/**
 * Normalizes text by removing redundant spacing for dictionary lookup.
 */
export const normalizePhrase = (text: string): string => {
  return text.trim().replace(/\s+/g, ' ');
};

/**
 * Translates a phrase or returns undefined if no static translation exists.
 */
export const translatePhrase = (phrase: string): string | undefined => {
  if (!phrase || typeof phrase !== 'string') return undefined;
  const normalized = normalizePhrase(phrase);
  
  // Exact match
  if (universalPhraseDictionary[normalized]) {
    return universalPhraseDictionary[normalized];
  }

  // Case-insensitive match
  const lower = normalized.toLowerCase();
  for (const [key, value] of Object.entries(universalPhraseDictionary)) {
    if (key.toLowerCase() === lower) {
      return value;
    }
  }

  return undefined;
};
